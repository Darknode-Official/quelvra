test("special functions match mpmath to 1e-13 relative", () => {
  for (const [name, x, want] of REF) {
    const got = S[name](x);
    const err = Math.abs(got - want) / Math.max(Math.abs(want), 1e-300);
    ok(err < 1e-13, `${name}(${x}) = ${got}, want ${want} (rel err ${err})`);
  }
});
test("special functions return NaN outside their real domain", () => {
  for (const [f, x] of [["Ci", -1], ["Chi", 0], ["li", -2], ["lambertw", -1], ["Ei", 0]]) ok(Number.isNaN(S[f](x)), f + "(" + x + ")");
});
test("identities: W(x e^x) = x, Si odd, li(x) = Ei(ln x)", () => {
  for (const x of [-0.9, -0.2, 0.5, 3, 10]) ok(Math.abs(S.lambertw(x * Math.exp(x)) - x) < 1e-13 * Math.max(1, Math.abs(x)));
  for (const x of [0.3, 5, 17]) ok(S.Si(-x) === -S.Si(x));
  for (const x of [0.5, 2, 30]) ok(Math.abs(S.li(x) - S.Ei(Math.log(x))) < 1e-15 * Math.max(1, Math.abs(S.li(x))));
});
test("the verifier evaluates the special functions the integrator emits", () => {
  for (const [src, x, want] of [["Si(x)", 2, 1.6054129768026948], ["Ei(x)", 1, 1.8951178163559368], ["FresnelS(x)", 1, 0.4382591473903548], ["erfi(x)", 1, 1.6504257587975429], ["lambertw(x)", 1, 0.5671432904097838]]) {
    const v = evalReal(parse(src), { x });
    ok(Math.abs(v - want) < 1e-13, src + " at " + x + " = " + v);
  }
});
test("special function names parse as functions, not products", () => {
  for (const n of ["Si", "Ci", "Shi", "Chi", "Ei", "li", "erfi", "erfc", "FresnelS", "FresnelC", "lambertw"]) {
    const t = parse(n + "(x)");
    ok(t.k === "fn" && t.name === n, n + " parsed as " + t.k);
  }
});
