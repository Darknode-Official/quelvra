const q = () => $("#q");
function autogrow() {
  const t = q();
  t.style.height = "auto";
  t.style.height = Math.min(t.scrollHeight + 2, window.innerHeight * 0.4) + "px";
}

let previewTimer = 0, previewSeq = 0, previewJob = null;
function schedulePreview() {
  clearTimeout(previewTimer);
  previewTimer = setTimeout(runPreview, 160);
}
async function runPreview() {
  const input = normalizeInput(q().value);
  const box = $("#preview");
  const seq = ++previewSeq;
  if (!input) { box.replaceChildren(); box.classList.remove("err"); return; }
  if (previewJob) previewJob.cancel();
  const job = bridge.preview(input);
  previewJob = job;
  try {
    const r = await job;
    if (seq !== previewSeq) return;
    box.classList.remove("err");
    const kids = [h("span", { class: "pv-label" }, "Reads as"), r.tree ? mathEl(r.tree, { display: false, label: "Input reads as" }) : h("span", { class: "pv-text" }, r.text || "")];
    for (const w of r.warnings || []) kids.push(h("div", { class: "warn-line" }, w.msg));
    box.replaceChildren(...kids);
  } catch (err) {
    if (seq !== previewSeq || !err || err.code === "CANCELLED") return;
    box.classList.add("err");
    box.replaceChildren(...syntaxErrorView(input, err));
  } finally {
    if (previewJob === job) previewJob = null;
  }
}

function syntaxErrorView(input, err) {
  const out = [];
  const pos = typeof err.pos === "number" ? Math.max(0, Math.min(err.pos, input.length)) : null;
  out.push(h("div", { class: "err-msg" }, err.message || "Could not read the input"));
  if (pos !== null) {
    const src = h("div", { class: "err-src", "aria-hidden": "true" });
    const bad = input.slice(pos, pos + 1) || " ";
    src.append(input.slice(0, pos), h("mark", null, bad), input.slice(pos + 1));
    out.push(src, h("span", { class: "sr-only" }, `Problem at character ${pos + 1}.`));
  }
  if (err.hint) out.push(h("div", { class: "err-hint" }, "Hint: " + err.hint));
  return out;
}

