function toggleTheme() {
  const next = effectiveTheme() === "dark" ? "light" : "dark";
  const followSystem = next === (sysDark() ? "dark" : "light");
  if (followSystem) document.documentElement.removeAttribute("data-theme");
  else document.documentElement.setAttribute("data-theme", next);
  try { if (followSystem) localStorage.removeItem("quelvra-theme"); else localStorage.setItem("quelvra-theme", next); } catch (_) {}
  store.setPref("theme", followSystem ? "system" : next);
  updateThemeButton(); // also redraws the graph, which reads its colours from CSS
}

