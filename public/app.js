// ---------------- solving ----------------
function setBusy(on, stage = "Computing") {
  const box = $("#progress");
  box.hidden = !on;
  $("#btn-solve").disabled = on;
  clearInterval(state.tick);
  if (on) {
    state.jobStart = performance.now();
    $("#progress-text").textContent = stage;
    const upd = () => { $("#progress-time").textContent = ((performance.now() - state.jobStart) / 1000).toFixed(1) + " s"; };
    upd();
    state.tick = setInterval(upd, 100);
  }
}
const STAGE_TEXT = (s) => String(s || "computing").replace(/^./, (c) => c.toUpperCase());

async function runSolve() {
  const raw = q().value;
  const input = normalizeInput(raw);
  if (!input) { q().focus(); return; }
  if (state.job) state.job.cancel();
  $("#empty").hidden = true;
  setBusy(true, "Starting");
  const job = bridge.solve(input, opts(), { onProgress: (stage) => { if (state.job === job) $("#progress-text").textContent = STAGE_TEXT(stage); } });
  state.job = job;
  try {
    const result = await job;
    if (state.job !== job) return;
    state.lastResult = result;
    state.lastInput = input;
    renderResult(result, input);
    saveHistory(raw, result);
  } catch (err) {
    if (state.job !== job) return;
    if (err && err.code === "CANCELLED") renderNotice("Cancelled. The computation was stopped and the worker restarted.");
    else renderError(err || {}, input);
  } finally {
    if (state.job === job) { state.job = null; setBusy(false); }
  }
}

async function runNumeric(input) {
  if (state.job) state.job.cancel();
  setBusy(true, "Numeric approximation");
  const job = bridge.numeric(input, opts(), { onProgress: (s) => { if (state.job === job) $("#progress-text").textContent = STAGE_TEXT(s); } });
  state.job = job;
  try {
    const result = await job;
    if (state.job !== job) return;
    renderResult(result, input);
  } catch (err) {
    if (state.job !== job) return;
    if (err && err.code === "CANCELLED") renderNotice("Cancelled.");
    else renderError(err || {}, input, true);
  } finally {
    if (state.job === job) { state.job = null; setBusy(false); }
  }
}

