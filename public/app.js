function cwLine(value = "") {
  const li = h("li", { class: "cw-line" });
  const input = h("input", { type: "text", class: "field", name: "line", spellcheck: "false", autocomplete: "off" });
  input.value = value;
  input.addEventListener("keydown", (e) => {
    if (e.key === "Enter") {
      e.preventDefault();
      if (e.ctrlKey || e.metaKey) { runCheck(); return; }
      const nl = cwLine();
      li.after(nl);
      renumber();
      nl.querySelector("input").focus();
    }
  });
  const del = h("button", { type: "button", class: "btn ghost", onclick: () => { if ($("#cw-lines").children.length > 1) { li.remove(); renumber(); } else input.value = ""; } }, icon("x"));
  li.append(h("span", { class: "cw-n", "aria-hidden": "true" }), input, del, h("div", { class: "cw-status", "aria-live": "polite" }));
  return li;
}
function renumber() {
  [...$("#cw-lines").children].forEach((li, i) => {
    li.querySelector(".cw-n").textContent = String(i + 1);
    li.querySelector("input").setAttribute("aria-label", `Line ${i + 1}`);
    li.querySelector(".btn").setAttribute("aria-label", `Remove line ${i + 1}`);
  });
}
function setLines(lines) {
  $("#cw-lines").replaceChildren(...lines.map((l) => cwLine(l)));
  renumber();
}
async function runCheck() {
  const lis = [...$("#cw-lines").children];
  const entries = lis.map((li) => ({ li, text: li.querySelector("input").value.trim() })).filter((e) => e.text);
  for (const li of lis) { li.className = "cw-line"; li.querySelector(".cw-status").replaceChildren(); }
  if (!entries.length) { $("#cw-summary").textContent = "Type at least two lines."; return; }
  if (state.job) state.job.cancel();
  $("#cw-summary").textContent = "Checking...";
  const job = bridge.checkWork(entries.map((e) => e.text), opts());
  state.job = job;
  $("#cw-check").disabled = true;
  try {
    const r = await job;
    const rows = r.lines || [];
    rows.forEach((row, i) => {
      const e = entries[row.index ?? i];
      if (!e) return;
      const st = row.status || "unknown";
      e.li.classList.add("st-" + st);
      const map = { ok: ["check", "st-ok", "Follows"], start: ["dash", "st-mut", "Start"], mistake: ["alert", "st-bad", "Mistake"], syntax: ["alert", "st-bad", "Cannot read"], unknown: ["dash", "st-warn", "Not checked"] };
      const [ic, cls, word] = map[st] || map.unknown;
      e.li.querySelector(".cw-status").replaceChildren(h("span", { class: cls }, icon(ic)), h("b", { class: cls }, word), h("span", null, row.message ? " " + row.message : ""));
    });
    const fm = typeof r.firstMistake === "number" && r.firstMistake >= 0 ? r.firstMistake : -1;
    $("#cw-summary").textContent = fm >= 0 ? `First mistake on line ${fm + 1}.` : rows.some((x) => x.status === "syntax" || x.status === "unknown") ? "No mistakes found, but some lines could not be checked." : "Every line follows from the one before.";
  } catch (err) {
    $("#cw-summary").textContent = err && err.code === "CANCELLED" ? "Cancelled." : "Could not check: " + ((err && err.message) || "unknown error");
  } finally {
    if (state.job === job) state.job = null;
    $("#cw-check").disabled = false;
  }
}

