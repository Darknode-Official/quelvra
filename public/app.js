async function copyText(text, what) {
  let ok = false;
  try { await navigator.clipboard.writeText(text); ok = true; } catch (_) {
    try {
      const ta = h("textarea", { class: "sr-only", "aria-hidden": "true" });
      ta.value = text;
      document.body.append(ta);
      ta.select();
      ok = document.execCommand("copy");
      ta.remove();
    } catch (_) { ok = false; }
  }
  toast(ok ? `Copied ${what}` : "Copy failed: select the text manually");
}

// ---------------- math rendering ----------------
// A "math value" is a tree record from the bridge ({ $tree, text, latex, node }), a raw tree, or text.
const nodeOf = (v) => (v && v.$tree ? v.node : v && typeof v === "object" && typeof v.k === "string" ? v : null);
const textOf = (v) => (v == null ? "" : typeof v === "string" ? v : typeof v === "number" ? String(v) : v.$tree ? v.text : v.k ? safeText(v) : String(v));
function safeText(node) {
  try { return toMathMLText(node); } catch (_) { return ""; }
}
// Only used for raw page-side trees (records already carry text).
let printMod = null;
import("./engine/print.js").then((m) => { printMod = m; }).catch(() => {});
function toMathMLText(node) { return printMod ? printMod.toText(node) : ""; }

function mathEl(v, { display = false, highlight = null, label = "" } = {}) {
  const wrap = h("span", { class: "m" });
  const node = nodeOf(v);
  const text = textOf(v);
  if (node) {
    let markup = "";
    try { markup = toMathML(node, { display, highlight }); } catch (_) { markup = ""; }
    if (markup) {
      const holder = h("span", { "aria-hidden": "true" });
      holder.innerHTML = markup; // markup is generated by mathml.js with every text node escaped
      wrap.append(holder, h("span", { class: "sr-only", text: (label ? label + ": " : "") + text }));
      return wrap;
    }
  }
  wrap.append(h("code", { class: "mono" }, text));
  return wrap;
}

