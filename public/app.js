function numberOf(v) {
  if (typeof v === "number") return v;
  if (typeof v === "string") { const n = Number(v); return Number.isFinite(n) ? n : NaN; }
  const node = nodeOf(v);
  if (node) { try { return compile(node, [])(); } catch (_) { return NaN; } }
  return NaN;
}

function graphCard(r) {
  const g = r.graph;
  if (!g || !Array.isArray(g.exprs) || !g.exprs.length) return null;
  const exprs = g.exprs.map(nodeOf).filter(Boolean);
  if (!exprs.length) return null;
  const card = h("section", { class: "card graph-card", "aria-labelledby": "graph-h" }, h("h2", { id: "graph-h" }, "Graph"));
  const host = h("div");
  card.append(host);
  const marks = (g.marks || []).map((m) => ({ x: numberOf(m.x), y: numberOf(m.y), label: textOf(m.label ?? ""), kind: m.kind || "point" })).filter((m) => Number.isFinite(m.x) && Number.isFinite(m.y));
  const asymptotes = (g.asymptotes || []).map((a) => (typeof a === "object" && a && !a.$tree && !a.k ? { x: a.x !== undefined ? numberOf(a.x) : undefined, y: a.y !== undefined ? numberOf(a.y) : undefined } : { x: numberOf(a) })).filter((a) => Number.isFinite(a.x) || Number.isFinite(a.y));
  const poles = (g.poles || []).map(numberOf).filter(Number.isFinite);
  // create after insertion so the canvas can measure itself
  queueMicrotask(() => {
    try {
      state.graph = createGraph(host);
      state.graph.set({ exprs, marks, asymptotes, poles });
    } catch (e) {
      host.replaceChildren(h("p", { class: "muted" }, "The graph could not be drawn: " + (e.message || e)));
    }
  });
  return card;
}

