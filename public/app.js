function insertAtCursor(template) {
  const t = q();
  const s = t.selectionStart ?? t.value.length, e = t.selectionEnd ?? t.value.length;
  const sel = t.value.slice(s, e);
  const i = template.indexOf("|");
  const text = i < 0 ? template : template.slice(0, i) + sel + template.slice(i + 1);
  t.value = t.value.slice(0, s) + text + t.value.slice(e);
  const caret = s + (i < 0 ? text.length : i + sel.length);
  t.focus();
  t.setSelectionRange(caret, caret);
  autogrow();
  schedulePreview();
}

